export function bucketColor(id) {
  return BUCKET_COLORS[id] || '#6f93a8'
}

export function bucketLabel(id) {
  const found = SCRIPTS.find((s) => s.id === id)
  if (found) return found.label
  return (
    {
      en: 'English',
      hi: 'Hindi (देवनागरी)',
      hinglish: 'Hinglish (Roman Hindi)',
      shared: 'Shared (both)',
      other: 'Other / not in dictionary',
      num: 'Numbers'
    }[id] || id
  )
}

// Sorted list of [id, label, count, pct] rows for detailed display.
export function mixRows(text) {
  const { buckets, pct } = analyzeText(text)
  const rows = []
  for (const [id, count] of Object.entries(buckets)) {
    if (id === 'num' || !count) continue
    rows.push({ id, label: bucketLabel(id), count, pct: pct[id] })
  }
  rows.sort((a, b) => b.count - a.count)
  return rows
}

// "hinglish" if an Indian mixed Hindi+English sentence is detected at all.
export function dominantBucket(text) {
  const { buckets, total } = analyzeText(text)
  if (!total) return null
  const entries = Object.entries(buckets).filter(([k]) => k !== 'num')
  entries.sort((a, b) => b[1] - a[1])
  const top = entries[0]
  if (entries.length > 1 && entries[1][1] === top[1]) return 'mixed'
  return top[0]
}

// True when Latin script + clearly carries romanized-Hindi words (used to
// decide the Hinglish→Hindi pivot translation route).
export function isHinglishText(text) {
  const { buckets, total } = analyzeText(text)
  if (!total) return false
  const latinOnly = !buckets.hi && !SCRIPTS.some((s) => s.id !== 'hi' && buckets[s.id])
  return latinOnly && (buckets.hinglish || 0) > 0
}

// Expose the English set so the translate tool can protect English words
// (the "keep my English words" mix option).
export function isEnglishWord(word) {
  return EN_SET.has(normalizeEn(word))
}

export function hasDevanagari(text) {
  return /[\u0900-\u097F]/.test(text)
}
